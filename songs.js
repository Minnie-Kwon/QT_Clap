//
//  멜로디 적는 법: '음이름:박자' 를 띄어쓰기로 이어 써요. 한 마디 = 4박
//   예) 'C5:1 C5:1 G5:2'  → 도(1박) 도(1박) 솔(2박)
//   음이름: C 도, D 레, E 미, F 파, G 솔, A 라, B 시 / 숫자 5 = 가운데 도보다 한 옥타브 위
//   '-:1' 은 1박 쉼표
//  코드: 마디마다 [앞 2박 코드, 뒤 2박 코드]
// =====================================================================

const NOTE = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
const midi = (name) => {
  const m = name.match(/^([A-G])(#?)(\d)$/);
  return 12 * (Number(m[3]) + 1) + NOTE[m[1]] + (m[2] ? 1 : 0);
};
// '음:박자 음:박자 …' → [[시작 박, 길이, MIDI 번호], …]
const bar = (text) => {
  let beat = 0;
  const out = [];
  for (const tok of text.trim().split(/\s+/)) {
    const [n, len] = tok.split(':');
    if (n !== '-') out.push([beat, Number(len), midi(n)]);
    beat += Number(len);
  }
  return out;
};

